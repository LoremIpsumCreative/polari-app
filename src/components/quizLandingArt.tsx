export function ModeGlyph({ name, s, color }: { name: ModeGlyphName; s: number; color: string }) {
  const g = MODE_GLYPHS[name];
  return (
    <Svg
      width={g.w * s}
      height={g.h * s}
      viewBox={`0 0 ${g.w} ${g.h}`}
      style={{ position: 'absolute', left: g.dx * s, top: g.dy * s }}
      pointerEvents="none"
    >
      <Path d={g.d} fill={color} />
    </Svg>
  );
}

// The landing's two purple blobs (the headline panel and the signpost board).
// Their gold edge is an INSIDE stroke in Figma, which SVG has no direct
// equivalent for — drawing it at double weight and clipping to the path itself
// yields the same result, and keeps the shape's outer edge exactly on its box.
export function Blob({
  id,
  d,
  w,
  h,
  s,
  strokeWidth = 5,
  vw,
  vh,
  edgeFrom = '#F7DA75',
  edgeTo = '#F5CD47',
  offsetX = 0,
  offsetY = 0,
}: {
  id: string;
  d: string;
  w: number;
  h: number;
  s: number;
  strokeWidth?: number;
  // The path's own authoring box, when it differs from the size the frame
  // renders it at — the shape then scales instead of being cropped.
  vw?: number;
  vh?: number;
  // Each shape carries its own edge gradient in the frame: the headline blob
  // runs gold to deeper gold, the signpost board and Play Again banner run
  // cream to gold. They are not interchangeable.
  edgeFrom?: string;
  edgeTo?: string;
  // Where the exported shape sits inside the frame's slot.
  offsetX?: number;
  offsetY?: number;
}) {
  return (
    <Svg
      width={w * s}
      height={h * s}
      viewBox={`0 0 ${vw ?? w} ${vh ?? h}`}
      style={{ position: 'absolute', left: offsetX * s, top: offsetY * s }}
      pointerEvents="none"
    >
      <Defs>
        <LinearGradient id={`${id}Fill`} x1="0" y1="0" x2="0" y2="1">
          <Stop offset="0" stopColor="#493B8B" />
          <Stop offset="1" stopColor="#352C63" />
        </LinearGradient>
        <LinearGradient id={`${id}Edge`} x1="0" y1="0" x2="0" y2="1">
          <Stop offset="0" stopColor={edgeFrom} />
          <Stop offset="1" stopColor={edgeTo} />
        </LinearGradient>
      </Defs>
      <Path
        d={d}
        fill={`url(#${id}Fill)`}
        stroke={`url(#${id}Edge)`}
        strokeWidth={strokeWidth}
      />
    </Svg>
  );
}
